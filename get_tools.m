function tools = get_tools()
%GET_TOOLS Build ai-agent-sdk tool definitions.

    readFile = aisdk.llmTool(@tool_read_file, ...
        Name="read_file", ...
        Description="Read the contents of a text file.", ...
        InputArguments=aisdk.llmToolArgument("path", ...
            DataType="string", ...
            Description="Absolute or relative path to the file."));

    writeFile = aisdk.llmTool(@tool_write_file, ...
        Name="write_file", ...
        Description="Write text content to a file, creating parent directories if needed.", ...
        RequiresConfirm="Always", ...
        InputArguments=[
            aisdk.llmToolArgument("path", DataType="string", Description="Absolute or relative path to write.")
            aisdk.llmToolArgument("content", DataType="string", Description="Text content to write.")
        ]);

    listFiles = aisdk.llmTool(@tool_list_files, ...
        Name="list_files", ...
        Description="List files and directories at a path.", ...
        InputArguments=[
            aisdk.llmToolArgument("path", DataType="string", Description="Directory path to list.")
            aisdk.llmToolArgument("recursive", DataType="boolean", Required=false, Description="Whether to list recursively.")
        ]);

    askUser = aisdk.llmTool(@tool_ask_user, ...
        Name="ask_user", ...
        Description="Ask the user a clarifying question and wait for an answer.", ...
        InputArguments=aisdk.llmToolArgument("question", ...
            DataType="string", ...
            Description="Question to ask the user."));

    evalMatlab = aisdk.llmTool(@tool_evaluate_matlab_code, ...
        Name="evaluate_matlab_code", ...
        Description="Execute MATLAB code through the MCP Core Server.", ...
        InputArguments=aisdk.llmToolArgument("code", ...
            DataType="string", ...
            Description="MATLAB code to execute."));

    detectToolboxes = aisdk.llmTool(@tool_detect_matlab_toolboxes, ...
        Name="detect_matlab_toolboxes", ...
        Description="List installed MATLAB toolboxes and versions.");

    checkCode = aisdk.llmTool(@tool_check_matlab_code, ...
        Name="check_matlab_code", ...
        Description="Run MATLAB Code Analyzer on a MATLAB file.", ...
        InputArguments=aisdk.llmToolArgument("script_path", ...
            DataType="string", ...
            Description="Path to the MATLAB .m file to analyze."));

    runFile = aisdk.llmTool(@tool_run_matlab_file, ...
        Name="run_matlab_file", ...
        Description="Run a MATLAB .m file through the MCP Core Server.", ...
        InputArguments=aisdk.llmToolArgument("script_path", ...
            DataType="string", ...
            Description="Path to the MATLAB .m file to run."));

    runTest = aisdk.llmTool(@tool_run_matlab_test_file, ...
        Name="run_matlab_test_file", ...
        Description="Run a MATLAB unit test file through the MCP Core Server.", ...
        InputArguments=aisdk.llmToolArgument("script_path", ...
            DataType="string", ...
            Description="Path to the MATLAB unit test .m file."));

    tools = [readFile, writeFile, listFiles, askUser, evalMatlab, ...
        detectToolboxes, checkCode, runFile, runTest];
end
